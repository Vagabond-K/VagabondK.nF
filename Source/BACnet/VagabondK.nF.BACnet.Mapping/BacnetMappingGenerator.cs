    /// <summary>AV/BV 모델에서 직접 접근하는 Device 저장소를 생성합니다.</summary>
    /// <remarks>최상위 비제네릭 partial class에 지정하며, 모델 안에 중첩 <c>BacnetStore</c> 클래스(<c>IBacnetValueStore</c> 구현)가 생성됩니다.
    /// <see cref=""BacnetPointAttribute""/>가 붙은 멤버가 1~64개 있어야 합니다.</remarks>
    [global::System.AttributeUsage(global::System.AttributeTargets.Class, AllowMultiple = false, Inherited = false)]
    internal sealed class BacnetMapAttribute : global::System.Attribute { }
    /// <summary>float는 Analog Value, bool은 Binary Value의 Present_Value에 연결합니다.</summary>
    /// <remarks>읽기 가능한 인스턴스 필드나 속성에 지정합니다. 같은 객체 종류 안에서 인스턴스 번호는 중복될 수 없습니다.</remarks>
