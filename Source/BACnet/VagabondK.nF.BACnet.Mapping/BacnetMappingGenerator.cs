using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace VagabondK.nF.BACnet.Mapping.Generator
{
    /// <summary>AV/BV 모델에서 직접 접근하는 BACnet Device 저장소를 생성합니다.</summary>
    [Generator(LanguageNames.CSharp)]
    public sealed class BacnetMappingGenerator : IIncrementalGenerator
    {
        private const string Prefix = "VagabondK.nF.BACnet.Mapping.";
        private const string Runtime = "global::VagabondK.nF.BACnet.";
        private const string Bits = "global::VagabondK.nF.BACnet.Mapping.Generated.RealBits.";
        private static readonly DiagnosticDescriptor Shape = Error("VKBN001", "BACnet 매핑 클래스");
        private static readonly DiagnosticDescriptor Member = Error("VKBN002", "BACnet 매핑 멤버");
        private static readonly DiagnosticDescriptor Options = Error("VKBN003", "BACnet 객체 및 품질");
        private static readonly DiagnosticDescriptor Duplicate = Error("VKBN004", "BACnet 객체 중복");
        private static readonly DiagnosticDescriptor Collision = Error("VKBN005", "BACnet 생성 이름 충돌");

        private static DiagnosticDescriptor Error(string id, string title)
        {
            return new DiagnosticDescriptor(id, title, "{0}", "BacnetMapping", DiagnosticSeverity.Error, true);
        }

        /// <summary>매핑 선언 검색과 소스 생성기를 등록합니다.</summary>
        /// <param name="context">컴파일러 초기화 컨텍스트입니다.</param>
        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            context.RegisterPostInitializationOutput(c => c.AddSource("BacnetAttributes.g.cs",
                SourceText.From(VagabondK.nF.Mapping.Generator.MappingAttributeSource.ForBuild(Attributes), Encoding.UTF8)));
            var models = context.SyntaxProvider.ForAttributeWithMetadataName(Prefix + "BacnetMapAttribute",
                (node, _) => node is TypeDeclarationSyntax, (syntax, _) => (INamedTypeSymbol)syntax.TargetSymbol);
            context.RegisterSourceOutput(models.Collect(), (output, symbols) =>
            {
                var seen = new HashSet<ISymbol>(SymbolEqualityComparer.Default);
                bool analog = false;
                int index = 0;
                foreach (var model in symbols.OrderBy(s => s.ToDisplayString(), StringComparer.Ordinal))
                    if (seen.Add(model))
                        analog |= Generate(output, model, "BacnetMap" + (index++).ToString("D4", CultureInfo.InvariantCulture) + ".g.cs");
                if (analog)
                {
                    using (var reader = new StreamReader(typeof(BacnetMappingGenerator).Assembly.GetManifestResourceStream("RealBits.cs")))
                        output.AddSource("BacnetRealBits.g.cs", SourceText.From("// <auto-generated/>\n" +
                            reader.ReadToEnd().Replace("namespace VagabondK.nF.Internal", "namespace VagabondK.nF.BACnet.Mapping.Generated"), Encoding.UTF8));
                }
            });
        }

        private static bool Generate(SourceProductionContext output, INamedTypeSymbol model, string hint)
        {
            bool failed = false;
            Action<DiagnosticDescriptor, ISymbol, string> report = (descriptor, symbol, message) =>
            {
                output.ReportDiagnostic(Diagnostic.Create(descriptor, symbol.Locations.FirstOrDefault(), message));
                failed = true;
            };
            if (model.TypeKind != TypeKind.Class || model.IsStatic || model.IsAbstract || model.IsFileLocal ||
                model.IsGenericType || model.ContainingType != null || model.BaseType?.SpecialType != SpecialType.System_Object ||
                model.DeclaringSyntaxReferences.Any(r => !(r.GetSyntax() is ClassDeclarationSyntax c) ||
                    !c.Modifiers.Any(SyntaxKind.PartialKeyword)))
            {
                report(Shape, model, "최상위 비제네릭·비상속 partial class가 필요합니다.");
                return false;
            }
            if (model.Name == "BacnetStore" || model.GetMembers("BacnetStore").Length > 0)
                report(Collision, model, "BacnetStore는 생성 저장소가 사용하는 이름입니다.");
            var points = new List<Point>();
            foreach (var symbol in model.GetMembers())
            {
                var attributes = symbol.GetAttributes().Where(a => a.AttributeClass?.ToDisplayString() == Prefix + "BacnetPointAttribute" ||
                    a.AttributeClass?.ToDisplayString() == Prefix + "BacnetAnalogValueAttribute" ||
                    a.AttributeClass?.ToDisplayString() == Prefix + "BacnetBinaryValueAttribute").ToArray();
                if (attributes.Length == 0) continue;
                if (attributes.Length != 1)
                {
                    report(Member, symbol, "한 멤버에는 BACnet 매핑 특성을 하나만 지정하십시오.");
                    continue;
                }
                var attribute = attributes[0];
                var property = symbol as IPropertySymbol;
                var field = symbol as IFieldSymbol;
                bool writable = attribute.NamedArguments.Any(a => a.Key == "Writable" && a.Value.Value is bool value && value);
                if (!Readable(symbol) || (writable && (property != null ?
                    property.SetMethod == null || property.SetMethod.IsInitOnly : field.IsReadOnly || field.IsConst)))
                {
                    report(Member, symbol, "읽기 가능한 인스턴스 필드/속성이 필요하며 Writable 멤버에는 setter 또는 변경 가능한 필드가 필요합니다.");
                    continue;
                }
                var type = property?.Type ?? field.Type;
                bool binary = type.SpecialType == SpecialType.System_Boolean;
                if ((!binary && type.SpecialType != SpecialType.System_Single) ||
                    (attribute.AttributeClass.Name == "BacnetAnalogValueAttribute" && binary) ||
                    (attribute.AttributeClass.Name == "BacnetBinaryValueAttribute" && !binary))
                {
                    report(Member, symbol, "AV는 float, BV는 bool만 지원합니다.");
                    continue;
                }
                if (attribute.ConstructorArguments.Length != 1 || !(attribute.ConstructorArguments[0].Value is uint instance) ||
                    instance > 4194302 || attribute.NamedArguments.Any(a => a.Value.Kind == TypedConstantKind.Error))
                {
                    report(Options, symbol, "객체 instance는 0~4194302 범위여야 합니다.");
                    continue;
                }
                string quality = null;
                var qualityOption = attribute.NamedArguments.FirstOrDefault(a => a.Key == "Quality");
                if (qualityOption.Key != null)
                {
                    quality = qualityOption.Value.Value as string;
                    var qualityMembers = quality == null ? new ISymbol[0] : model.GetMembers(quality).ToArray();
                    if (qualityMembers.Length != 1 || !Readable(qualityMembers[0]) ||
                        (qualityMembers[0] is IPropertySymbol qp ? qp.Type : ((IFieldSymbol)qualityMembers[0]).Type).SpecialType != SpecialType.System_Boolean)
                    {
                        report(Options, symbol, "Quality는 같은 모델의 읽기 가능한 bool 인스턴스 필드/속성 이름이어야 합니다.");
                        continue;
                    }
                }
                points.Add(new Point(symbol, instance, binary, writable, quality));
            }
            if (points.Count < 1 || points.Count > 64)
                report(Member, model, "기존 Device 계약에 따라 1~64개 AV/BV 객체가 필요합니다.");
            points.Sort((a, b) => a.Id.CompareTo(b.Id));
            for (int i = 1; i < points.Count; i++)
                if (points[i].Id == points[i - 1].Id)
                    report(Duplicate, points[i].Symbol, "동일 객체 종류와 instance가 중복됩니다: " + points[i - 1].Symbol.Name);
            if (failed) return false;
            var b = new StringBuilder("// <auto-generated/>\n");
            if (!model.ContainingNamespace.IsGlobalNamespace)
                b.Append("namespace ").Append(model.ContainingNamespace.ToDisplayString()).AppendLine(" {");
            b.Append("partial class @").Append(model.Name).AppendLine(" {");
            b.AppendLine("/// <summary>모델 값과 품질을 같은 잠금 안에서 읽는 고정 AV/BV 저장소입니다.</summary>");
            b.AppendLine("/// <remarks>객체는 종류(AV 다음 BV)별로 인스턴스 번호의 오름차순으로 정렬됩니다. 앱도 모델을 읽고 쓸 때 생성자에 전달한 같은 잠금을 사용해야 값과 품질을 일관되게 읽을 수 있습니다.</remarks>");
            b.Append("public sealed class BacnetStore : ").Append(Runtime).AppendLine("IBacnetValueStore {");
            b.Append("private readonly ").Append(model.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)).AppendLine(" _model;");
            b.AppendLine("private readonly object _sync;");
            b.Append("private readonly ").Append(Runtime).AppendLine("BacnetObject[] _objects;");
            b.AppendLine("/// <summary>모델과 앱이 공유하는 잠금 객체를 지정하여 직접 접근 저장소를 생성합니다.</summary>");
            b.AppendLine("/// <param name=\"model\">앱이 소유하는 모델입니다.</param>");
            b.AppendLine("/// <param name=\"syncRoot\">앱에서도 모델 접근 시 사용하는 잠금 객체입니다.</param>");
            b.AppendLine("/// <exception cref=\"global::System.ArgumentNullException\">모델 또는 잠금 객체가 null입니다.</exception>");
            b.Append("public BacnetStore(").Append(model.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)).AppendLine(" model, object syncRoot) {");
            b.AppendLine("if (model == null) throw new global::System.ArgumentNullException(\"model\");");
            b.AppendLine("if (syncRoot == null) throw new global::System.ArgumentNullException(\"syncRoot\");");
            b.AppendLine("_model = model; _sync = syncRoot;");
            b.Append("_objects = new ").Append(Runtime).AppendLine("BacnetObject[] {");
            foreach (var point in points)
                b.Append("new ").Append(Runtime).Append("BacnetObject(").Append(point.Instance).Append("U, ")
                    .Append(point.Binary ? "true" : "false").Append(", ").Append(point.Writable ? "true" : "false").AppendLine("),");
            b.AppendLine("}; }");
            b.AppendLine("/// <inheritdoc/>");
            b.Append("public int Count { get { return ").Append(points.Count).AppendLine("; } }");
            b.AppendLine("private void CheckIndex(int index) { if (index < 0 || index >= Count) throw new global::System.ArgumentOutOfRangeException(\"index\"); }");
            b.AppendLine("/// <inheritdoc/>");
            b.Append("public ").Append(Runtime).AppendLine("BacnetObject GetObject(int index) { CheckIndex(index); return _objects[index]; }");
            b.AppendLine("/// <inheritdoc/>");
            b.Append("public ").Append(Runtime).AppendLine("BacnetSample Read(int index) { CheckIndex(index); lock (_sync) { switch (index) {");
            for (int i = 0; i < points.Count; i++)
            {
                var p = points[i];
                b.Append("case ").Append(i).Append(": return new ").Append(Runtime).Append("BacnetSample(");
                if (p.Binary) b.Append("_model.@").Append(p.Symbol.Name).Append(" ? 1U : 0U");
                else b.Append(Bits).Append("Encode(_model.@").Append(p.Symbol.Name).Append(")");
                b.Append(", ").Append(p.Quality == null ? "true" : "_model.@" + p.Quality).AppendLine(");");
            }
            b.AppendLine("default: throw new global::System.ArgumentOutOfRangeException(\"index\"); } } }");
            b.AppendLine("/// <inheritdoc/>");
            b.AppendLine("/// <remarks>setter나 필드를 통해 값을 즉시 반영합니다. 품질은 변경하지 않으며, 변경 되돌리기나 실제 장치의 동작 완료를 보장하지 않습니다.</remarks>");
            b.AppendLine("/// <exception cref=\"global::System.ArgumentOutOfRangeException\">인덱스가 범위를 벗어났거나, BV에 0/1 이외의 값 또는 AV에 NaN/무한대 비트가 전달되었습니다.</exception>");
            b.AppendLine("/// <exception cref=\"global::System.InvalidOperationException\">읽기 전용 객체에 쓰려고 했습니다.</exception>");
            b.AppendLine("public void QueueWrite(int index, uint bits) { CheckIndex(index);");
            b.AppendLine("if (!_objects[index].Writable) throw new global::System.InvalidOperationException(\"Read-only BACnet object.\");");
            b.AppendLine("if (_objects[index].Binary ? bits > 1U : (bits & 0x7f800000U) == 0x7f800000U) throw new global::System.ArgumentOutOfRangeException(\"bits\");");
            b.AppendLine("lock (_sync) { switch (index) {");
            for (int i = 0; i < points.Count; i++)
                if (points[i].Writable)
                    b.Append("case ").Append(i).Append(": _model.@").Append(points[i].Symbol.Name).Append(" = ")
                        .Append(points[i].Binary ? "bits != 0U" : Bits + "Decode(bits)").AppendLine("; return;");
            b.AppendLine("default: throw new global::System.InvalidOperationException(\"Read-only BACnet object.\"); } } }");
            b.AppendLine("} }");
            if (!model.ContainingNamespace.IsGlobalNamespace) b.AppendLine("}");
            output.AddSource(hint, SourceText.From(SyntaxFactory.ParseCompilationUnit(b.ToString()).NormalizeWhitespace().ToFullString() + "\n", Encoding.UTF8));
            return points.Any(p => !p.Binary);
        }

        private static bool Readable(ISymbol symbol)
        {
            if (symbol.IsStatic) return false;
            if (symbol is IPropertySymbol p)
                return !p.IsIndexer && p.ExplicitInterfaceImplementations.Length == 0 && !p.ReturnsByRef && !p.ReturnsByRefReadonly && p.GetMethod != null;
            return symbol is IFieldSymbol f && !f.IsConst;
        }

        private sealed class Point
        {
            internal Point(ISymbol symbol, uint instance, bool binary, bool writable, string quality)
            { Symbol = symbol; Instance = instance; Binary = binary; Writable = writable; Quality = quality; }
            internal ISymbol Symbol { get; }
            internal uint Instance { get; }
            internal bool Binary { get; }
            internal bool Writable { get; }
            internal string Quality { get; }
            internal uint Id { get { return ((Binary ? 5U : 2U) << 22) | Instance; } }
        }

        private const string Attributes = @"// <auto-generated/>
